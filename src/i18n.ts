export const locale = navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
const dictionary: Record<Key, string> = locale === "zh" ? zh : en;

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return dictionary[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}

export function errorText(code: string, message: string): string {
  const key = `error.${code}` as Key;
  return key in dictionary ? t(key) : t("error.unexpected", { message });
}
